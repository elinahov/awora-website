// Generates supabase/seed.sql from src/data/seed.js so the database and the bundled fallback stay in sync.
import { writeFileSync } from 'node:fs';
import { COLORS, COMBOS, COLLECTIONS, PRODUCTS } from '../src/data/seed.js';
import { pricingFromSeed } from '../src/lib/config.js';

const q = v => v == null ? 'null' : typeof v === 'object' ? `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb` : `'${String(v).replace(/'/g, "''")}'`;
const rows = (table, cols, list) =>
  `insert into public.${table} (${cols.join(', ')}) values\n` +
  list.map(r => `  (${cols.map(c => q(r[c])).join(', ')})`).join(',\n') +
  `\non conflict (${cols[0]}) do update set ${cols.slice(1).map(c => `${c} = excluded.${c}`).join(', ')};\n`;

const sorted = list => list.map((r, i) => ({ ...r, sort: i }));
const sql = [
  '-- Generated by scripts/build-seed.mjs. Do not edit by hand.',
  rows('colors', ['id', 'hex', 'name', 'sort'], sorted(COLORS)),
  rows('combos', ['id', 'name', 'base', 'pattern', 'accent', 'sort'], sorted(COMBOS)),
  rows('collections', ['id', 'name', 'color', 'sort'], sorted(COLLECTIONS)),
  rows('products', ['slug', 'category', 'kind', 'collection', 'name', 'blurb', 'defaults', 'sort'], sorted(PRODUCTS)),
  '-- Prices: inserted once, so edits made in /admin are not overwritten by re-running this file.',
  `insert into public.settings (key, value) values ('pricing', ${q(pricingFromSeed())})\non conflict (key) do nothing;\n`
].join('\n');
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log('wrote supabase/seed.sql');
